"""Prometheus metrics configuration for the application.

This module sets up and configures Prometheus metrics for monitoring the application.
"""

from prometheus_client import Counter, Histogram, Gauge
from starlette_prometheus import metrics, PrometheusMiddleware

# Request metrics
http_requests_total = Counter("http_requests_total", "Total number of HTTP requests", ["method", "endpoint", "status"])

http_request_duration_seconds = Histogram(
    "http_request_duration_seconds", "HTTP request duration in seconds", ["method", "endpoint"]
)

# Database metrics
db_connections = Gauge("db_connections", "Number of active database connections")

# DB thread-pool dispatch: time spent running each blocking DB op off-loop.
# Watching this histogram surfaces latency regressions introduced by a
# missing index or slow query even though the event loop no longer blocks.
db_operation_seconds = Histogram(
    "db_operation_seconds",
    "Wall-clock time of synchronous DB operations dispatched to the thread pool",
    ["op"],
    buckets=[0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5],
)

# Background tasks
background_task_failures_total = Counter(
    "background_task_failures_total",
    "Total number of background tasks that raised an unhandled exception",
    ["task_name"],
)

# Sandbox (Docker) executions — the only place untrusted code is allowed to run.
sandbox_executions_total = Counter(
    "sandbox_executions_total",
    "Total sandboxed code executions (Docker) by outcome",
    ["result"],  # result: success | failed | timeout | disabled
)
sandbox_execution_seconds = Histogram(
    "sandbox_execution_seconds",
    "Wall-clock time of a single sandboxed execution (container spawn + run)",
    buckets=[0.5, 1.0, 2.0, 5.0, 10.0, 30.0, 60.0, 120.0],
)

# Custom business metrics
orders_processed = Counter("orders_processed_total", "Total number of orders processed")

llm_inference_duration_seconds = Histogram(
    "llm_inference_duration_seconds",
    "Time spent processing LLM inference",
    ["model"],
    buckets=[0.1, 0.3, 0.5, 1.0, 2.0, 5.0],
)


llm_stream_duration_seconds = Histogram(
    "llm_stream_duration_seconds",
    "Time spent processing LLM stream inference",
    ["model"],
    buckets=[0.1, 0.5, 1.0, 2.0, 5.0, 10.0],
)

session_names_generated_total = Counter(
    "session_names_generated_total",
    "Total session names generated by the LLM",
    ["status"],  # "success" | "error"
)


# SDLC Orchestrator metrics
sdlc_agent_execution_seconds = Histogram(
    "sdlc_agent_execution_seconds",
    "SDLC Agent execution time in seconds",
    ["agent_name", "step", "status"],  # agent_name: supervisor/planner/coder/tester/reviewer, status: success/fail
    buckets=[0.5, 1.0, 2.0, 5.0, 10.0, 30.0, 60.0],
)

sdlc_agent_errors_total = Counter(
    "sdlc_agent_errors_total",
    "Total number of SDLC Agent errors",
    ["agent_name", "step"],
)

sdlc_human_interventions_total = Counter(
    "sdlc_human_interventions_total",
    "Total number of human interventions in SDLC workflow",
    ["agent_name"],  # agent_name: reviewer/coder/tester/supervisor
)

sdlc_security_issues_total = Counter(
    "sdlc_security_issues_total",
    "Total number of security issues found during scanning",
    ["severity", "agent_name"],  # severity: low/medium/high/critical
)

sdlc_token_usage_total = Counter(
    "sdlc_token_usage_total",
    "Total token usage for SDLC Agent operations",
    ["agent_name", "model"],
)

# LLM cost in USD — incremented per call by the LLMUsageCallbackHandler.
# Allows answering "how much did this task cost?" and "which agent is
# most expensive?" via PromQL aggregation.
sdlc_llm_cost_usd_total = Counter(
    "sdlc_llm_cost_usd_total",
    "Total LLM cost in USD for SDLC operations",
    ["agent_name", "model", "task_type"],
)

# Token usage split by prompt vs completion — enables cost composition
# analysis (e.g. is the cost dominated by long prompts or verbose outputs?).
sdlc_llm_token_usage_total = Counter(
    "sdlc_llm_token_usage_total",
    "LLM token usage by type (prompt/completion) for SDLC operations",
    ["agent_name", "model", "token_type"],
)

sdlc_workflow_completed_total = Counter(
    "sdlc_workflow_completed_total",
    "Total number of SDLC workflows completed",
    ["status", "task_type"],  # status: success/fail, task_type: new_feature/bug_fix/general
)

sdlc_workflow_duration_seconds = Histogram(
    "sdlc_workflow_duration_seconds",
    "SDLC workflow total duration in seconds",
    ["status"],
    buckets=[5.0, 10.0, 30.0, 60.0, 120.0, 300.0, 600.0],
)

sdlc_token_budget_remaining = Gauge(
    "sdlc_token_budget_remaining",
    "Remaining token budget for SDLC workflows",
    ["session_id"],
)

sdlc_workflow_retries_total = Counter(
    "sdlc_workflow_retries_total",
    "Total number of workflow retries due to failures",
    ["agent_name"],
)

sdlc_workspace_size_bytes = Gauge(
    "sdlc_workspace_size_bytes",
    "Current workspace size in bytes per thread",
    ["thread_id"],
)

sdlc_cleanup_count = Counter(
    "sdlc_cleanup_count",
    "Total number of resource cleanup operations",
    ["resource_type"],  # resource_type: images / knowledge_graph / workspace
)

sdlc_quota_rejections_total = Counter(
    "sdlc_quota_rejections_total",
    "Total number of quota rejection events",
    ["quota_type"],  # quota_type: workspace / images / tasks
)


def setup_metrics(app):
    """Set up Prometheus metrics middleware and endpoints.

    Args:
        app: FastAPI application instance
    """
    # Add Prometheus middleware
    app.add_middleware(PrometheusMiddleware)

    # Add metrics endpoint
    app.add_route("/metrics", metrics)
